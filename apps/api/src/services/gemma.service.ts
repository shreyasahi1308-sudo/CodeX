import { OpenAI } from 'openai';
import { z } from 'zod';
import { config } from '../config/index.js';
import { Career, AssessmentAnswers, TryActivity } from '../types/index.js';

// Gemma 4 Model Reference Configuration
export const GEMMA_MODEL = 'google/gemma-4-31B-it:novita';
export const HF_ROUTER_BASE_URL = 'https://router.huggingface.co/v1';
export const INFERENCE_TIMEOUT_MS = 15000;

let openaiClient: OpenAI | null = null;

function getOpenAIClient(): OpenAI | null {
  if (!config.hfToken) {
    return null;
  }
  if (!openaiClient) {
    openaiClient = new OpenAI({
      baseURL: HF_ROUTER_BASE_URL,
      apiKey: config.hfToken,
      timeout: INFERENCE_TIMEOUT_MS,
    });
  }
  return openaiClient;
}

// Zod schemas for structured output validation
export const CareerExplanationSchema = z.object({
  summary: z.string().min(10),
  interest_connections: z.array(z.string()).min(1),
  skills_to_explore: z.array(z.string()).min(1),
  questions_to_consider: z.array(z.string()).min(1),
  indian_pathway_guidance: z.string().min(10),
  limitations: z.string().min(10),
});

export type CareerExplanation = z.infer<typeof CareerExplanationSchema>;

export const ActivityEvaluationSchema = z.object({
  praise: z.string().min(10),
  key_insight: z.string().min(10),
  real_world_application: z.string().min(10),
  next_exploration_step: z.string().min(10),
});

export type ActivityEvaluation = z.infer<typeof ActivityEvaluationSchema>;

export interface AIResponseMeta {
  aiGenerated: boolean;
  model: string;
  timestamp: string;
  statusNote?: string;
}

/**
 * Explains career fit using Gemma 4 with deterministic fallback
 */
export async function explainCareerFit(
  career: Career,
  answers: AssessmentAnswers,
  scorePercent: number
): Promise<{ data: CareerExplanation; meta: AIResponseMeta }> {
  const client = getOpenAIClient();

  if (client) {
    try {
      const prompt = `You are an encouraging, realistic career counselor for Indian high school students (Classes 9–12).
Analyze why the career "${career.name}" in the "${career.clusterName}" cluster fits this student.

Verified Career Data:
- Summary: ${career.summary}
- Typical day: ${career.dayInLife.join('; ')}
- Class 11-12 Streams & Degrees: ${career.pathways.map(p => `${p.title} (${p.streamRequired})`).join(' | ')}
- Key Exams: ${career.pathways.flatMap(p => p.exams?.map(e => e.name) || []).join(', ') || 'Direct degree/merit based'}
- Salary benchmarks: Entry ${career.salaryRange.entry}, Mid ${career.salaryRange.mid}
- Caveats/Uncertainties: ${career.uncertainties.join('; ')}

Student Profile:
- Favorite Subjects: ${(answers.subjects || []).join(', ') || 'Not specified'}
- Skills to build: ${(answers.growthSkills || []).join(', ') || 'Not specified'}
- Work environments: ${(answers.environments || []).join(', ') || 'Not specified'}
- Calculated Profile Match: ${scorePercent}%

Respond ONLY with a valid JSON object matching this schema:
{
  "summary": "2-3 sentences explaining personal fit in encouraging, student-friendly tone",
  "interest_connections": ["Specific point 1 connecting their answers", "Specific point 2"],
  "skills_to_explore": ["Key skill 1 to build during school", "Key skill 2"],
  "questions_to_consider": ["Thoughtful reflective question 1 for the student", "Question 2"],
  "indian_pathway_guidance": "Clear advice on Class 11-12 stream choice and Indian entrance exams",
  "limitations": "Honest note on work hours, competition, or what match scores do not guarantee"
}`;

      const completion = await client.chat.completions.create({
        model: GEMMA_MODEL,
        messages: [{ role: 'user', content: prompt }],
        temperature: 0.3,
        max_tokens: 600,
        response_format: { type: 'json_object' },
      });

      const rawContent = completion.choices[0]?.message?.content;
      if (rawContent) {
        const parsed = JSON.parse(rawContent);
        const validated = CareerExplanationSchema.parse(parsed);
        return {
          data: validated,
          meta: {
            aiGenerated: true,
            model: GEMMA_MODEL,
            timestamp: new Date().toISOString(),
          },
        };
      }
    } catch (err: any) {
      console.warn(`[GemmaService] Live inference error (${err.status || err.message}). Using deterministic fallback.`);
    }
  }

  // Deterministic Fallback Engine
  const fallback = generateDeterministicExplanation(career, answers, scorePercent);
  return {
    data: fallback,
    meta: {
      aiGenerated: false,
      model: 'deterministic_engine_v1',
      timestamp: new Date().toISOString(),
      statusNote: 'Generated by transparent rule-based matching engine (Gemma API unavailable or credits exhausted).',
    },
  };
}

/**
 * Interactive "Ask Gemma" Career Mentor
 */
export async function askCareerMentor(
  career: Career,
  question: string,
  history: { role: 'user' | 'assistant'; content: string }[] = []
): Promise<{ reply: string; meta: AIResponseMeta }> {
  const client = getOpenAIClient();

  if (client) {
    try {
      const messages: OpenAI.Chat.ChatCompletionMessageParam[] = [
        {
          role: 'system',
          content: `You are Gemma, an insightful and honest career mentor for Indian high school students (Classes 9–12).
You are mentoring a student asking about the career "${career.name}".
Ground your answers strictly in these verified facts about the career:
- Title: ${career.name}
- Cluster: ${career.clusterName}
- Summary: ${career.summary}
- Daily reality: ${career.dayInLife.join('; ')}
- Pathways & Stream requirements: ${career.pathways.map(p => `${p.title} (${p.streamRequired}): ${p.steps.join(' -> ')}`).join(' | ')}
- Entrance Exams: ${career.pathways.flatMap(p => p.exams?.map(e => `${e.name} (${e.officialUrl})`) || []).join(', ') || 'Institute/Merit based'}
- Realistic Salaries: Entry ${career.salaryRange.entry}, Mid-career ${career.salaryRange.mid}
- Known Uncertainties: ${career.uncertainties.join('; ')}

Guardrails:
- Never predict the student's destiny or guarantee admission.
- Be supportive, realistic about competition, and concise (under 180 words).
- If asked about coaching or fees, advise consulting official institute websites and parents/teachers.`,
        },
        ...history.slice(-4).map(h => ({ role: h.role, content: h.content } as const)),
        { role: 'user', content: question },
      ];

      const completion = await client.chat.completions.create({
        model: GEMMA_MODEL,
        messages,
        temperature: 0.5,
        max_tokens: 350,
      });

      const reply = completion.choices[0]?.message?.content;
      if (reply) {
        return {
          reply,
          meta: {
            aiGenerated: true,
            model: GEMMA_MODEL,
            timestamp: new Date().toISOString(),
          },
        };
      }
    } catch (err: any) {
      console.warn(`[GemmaService] Mentor error (${err.status || err.message}). Using deterministic fallback.`);
    }
  }

  // Deterministic Mentor Fallback
  const fallbackReply = generateDeterministicMentorReply(career, question);
  return {
    reply: fallbackReply,
    meta: {
      aiGenerated: false,
      model: 'deterministic_engine_v1',
      timestamp: new Date().toISOString(),
      statusNote: 'Deterministic counselor guidance (AI offline).',
    },
  };
}

/**
 * Evaluates student reflection on signature interactive activity
 */
export async function evaluateActivityReflection(
  activity: TryActivity,
  userAction: any,
  reflectionAnswers: Record<string, string>
): Promise<{ data: ActivityEvaluation; meta: AIResponseMeta }> {
  const client = getOpenAIClient();

  if (client) {
    try {
      const prompt = `You are a career learning coach. A Class 9-12 student just completed the career activity "${activity.title}" for "${activity.area}".

Activity Context:
- Scenario: ${activity.scenario}
- Student's actions/results: ${JSON.stringify(userAction)}
- Student's self-reflection: ${JSON.stringify(reflectionAnswers)}

Respond with a JSON object matching this schema:
{
  "praise": "Warm 1-2 sentence acknowledging their effort and thoughtful reflection",
  "key_insight": "A professional insight connecting what they just did to real-world work in this field",
  "real_world_application": "How professionals handle this challenge in Indian or global companies",
  "next_exploration_step": "One actionable, low-stakes micro-experiment to explore this career further"
}`;

      const completion = await client.chat.completions.create({
        model: GEMMA_MODEL,
        messages: [{ role: 'user', content: prompt }],
        temperature: 0.4,
        max_tokens: 400,
        response_format: { type: 'json_object' },
      });

      const raw = completion.choices[0]?.message?.content;
      if (raw) {
        const parsed = JSON.parse(raw);
        const validated = ActivityEvaluationSchema.parse(parsed);
        return {
          data: validated,
          meta: {
            aiGenerated: true,
            model: GEMMA_MODEL,
            timestamp: new Date().toISOString(),
          },
        };
      }
    } catch (err: any) {
      console.warn(`[GemmaService] Activity evaluation error: ${err.message}. Using deterministic fallback.`);
    }
  }

  // Deterministic Evaluation Fallback
  const fallback: ActivityEvaluation = {
    praise: `Great job completing the "${activity.title}" micro-challenge! Taking the time to test-drive real tasks is the single best way to uncover what you actually enjoy.`,
    key_insight: `This activity highlights the core reality of ${activity.area}: balancing logical analysis with practical problem solving under constraints.`,
    real_world_application: `In industry, practitioners encounter these exact trade-offs every week, using iterative testing and peer reviews to optimize outcomes.`,
    next_exploration_step: `Check out the verified learning roadmaps and beginner activities on the career profile to explore further!`,
  };

  return {
    data: fallback,
    meta: {
      aiGenerated: false,
      model: 'deterministic_engine_v1',
      timestamp: new Date().toISOString(),
      statusNote: 'Deterministic reflection assessment.',
    },
  };
}

// ----------------- Deterministic Fallback Helpers -----------------

function generateDeterministicExplanation(
  career: Career,
  answers: AssessmentAnswers,
  scorePercent: number
): CareerExplanation {
  const subjectsStr = (answers.subjects || []).filter(s => career.subjects.includes(s)).map(s => s.replace(/-/g, ' ')).join(', ');
  const skillsStr = (answers.growthSkills || []).filter(s => career.developableSkills.includes(s)).map(s => s.replace(/-/g, ' ')).join(', ');
  const primaryPathway = career.pathways[0];
  const exams = primaryPathway?.exams?.map(e => e.name).join(', ') || 'college entrance / merit';

  return {
    summary: `Your profile shows a ${scorePercent}% affinity with ${career.name}. This reflects strong synergy between your work-style preferences and what this profession prioritizes day-to-day.`,
    interest_connections: [
      subjectsStr ? `Your affinity for ${subjectsStr} directly aligns with the academic core of this career.` : `Your interest in analytical and creative problem solving matches the day-to-day duties of ${career.name}.`,
      skillsStr ? `You expressed a strong desire to develop ${skillsStr}, which are high-leverage skills in this field.` : `The career heavily values ${career.skills.slice(0, 2).map(s => s.replace(/-/g, ' ')).join(' and ')}.`,
      `The day-to-day workflow (${career.dayInLife[0]}) matches your indicated work environment preferences.`
    ],
    skills_to_explore: [
      `Hands-on practice in ${career.developableSkills[0]?.replace(/-/g, ' ') || 'problem solving'} through school projects`,
      `Building foundational proficiency in ${career.subjects[0]?.replace(/-/g, ' ') || 'core science/commerce subjects'}`,
      `Developing strong communication skills to articulate ideas to peers and mentors`
    ],
    questions_to_consider: [
      `Would you enjoy spending 4-6 hours a day on tasks like "${career.dayInLife[0]}"?`,
      `How do you feel about the education timeline (${primaryPathway?.title || 'degree pathways'}) and exam milestones (${exams})?`,
      `Have you tried a hands-on activity or spoken with a professional in this field to test your assumptions?`
    ],
    indian_pathway_guidance: `For Class 11–12, review the required stream: ${primaryPathway?.streamRequired || 'Recommended stream'}. Verified examinations typically include: ${exams}. Always check official conducting agency sites for annual eligibility criteria.`,
    limitations: `This recommendation measures alignment between your current preferences and verified job profiles. It does not predict future academic scores, college seat allotment, or job market conditions 5 years from now.`
  };
}

function generateDeterministicMentorReply(career: Career, question: string): string {
  const q = question.toLowerCase();

  if (q.includes('stream') || q.includes('class 11') || q.includes('subject')) {
    const p = career.pathways[0];
    return `For ${career.name}, the recommended Class 11-12 preparation is: ${p?.streamRequired}. Key subjects typically include ${career.subjects.map(s => s.replace(/-/g, ' ')).join(', ')}. Check each university or institute for exact subject eligibility criteria.`;
  }

  if (q.includes('exam') || q.includes('entrance') || q.includes('jee') || q.includes('neet') || q.includes('clat')) {
    const exams = career.pathways.flatMap(p => p.exams || []);
    if (exams.length > 0) {
      return `Key verified entrance examinations for ${career.name} include: ${exams.map(e => `${e.name} (${e.officialUrl})`).join(', ')}. Dates and formats update annually on their respective official portals.`;
    }
    return `Admissions for ${career.name} commonly happen through central university entrance (like CUET-UG) or direct merit based on Class 12 board marks.`;
  }

  if (q.includes('salary') || q.includes('earn') || q.includes('money') || q.includes('package')) {
    return `In India, typical starter packages for ${career.name} range from ${career.salaryRange.entry}. With 5–8 years of proven experience, mid-career professionals typically earn ${career.salaryRange.mid}. Actual compensation varies based on portfolio, institute, and employer scale.`;
  }

  if (q.includes('hard') || q.includes('difficult') || q.includes('stress') || q.includes('work life')) {
    return `Like any high-impact career, ${career.name} comes with real trade-offs: ${career.uncertainties.join(' ')} Focusing on genuine curiosity and consistent skill building during Classes 9-12 makes the journey significantly more manageable.`;
  }

  return `Regarding ${career.name}: ${career.summary} In a typical day, professionals "${career.dayInLife[0]}". The standard pathway starts with: ${career.pathways[0]?.title} (${career.pathways[0]?.streamRequired}). Feel free to ask about specific exams, daily routines, or school subject combinations!`;
}
